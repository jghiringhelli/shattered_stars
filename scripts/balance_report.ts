/**
 * balance_report — the heavy balance pass on the real engine: faction
 * matrices (classic auto-fill, reinforced, 200-pt presets), Ace Duel
 * presets, the Dogfight default pairing, the AI difficulty curve per mode,
 * scenarios (seat bias, length; classic and reinforced) and every Skirmish
 * hull's value per point, each with 95 % intervals. Runs on every core
 * (scripts/balance/pool.ts) and writes docs/balance/latest.md.
 *
 * Usage: npm run balance:report -- [--sections classic,ace,...] [--scale 0.5]
 *        [--out docs/balance/latest.md] [--json <raw results file>] [--workers n]
 */

import * as fs from "fs";
import * as path from "path";
import { getQuickBuild } from "../src/data/SquadronPresets";
import {
  BALANCE_FACTIONS,
  FACTION_SHORT,
  listCost,
  skirmishAutoFillList,
} from "../src/simulation/balance/squadLists";
import { runPool } from "./balance/pool";
import { buildPlan, SECTIONS, type SectionId } from "./balance/plan";
import {
  renderAceSection,
  renderDifficultySection,
  renderDogfightSection,
  renderFactionSection,
  renderScenarioSection,
} from "./balance/render";
import { renderShipsSection } from "./balance/renderShips";

function arg(flag: string): string | undefined {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function listsSection(): string {
  const rows = BALANCE_FACTIONS.map((faction) => {
    const list = skirmishAutoFillList(faction);
    const ships = list.ships
      .map((s) => `${s.definitionId}${s.loadoutId ? ` (${s.loadoutId})` : ""}`)
      .join(", ");
    const preset = getQuickBuild(faction, 200);
    return `| ${FACTION_SHORT[faction]} | ${listCost(list)} | ${ships} | ${preset ? `${preset.name} ${preset.totalCost}` : "–"} |`;
  });
  return [
    "## Lists",
    "",
    "| faction | auto-fill cost (as flown) | auto-fill ships (default builds) | 200-pt preset |",
    "|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const requested = (arg("--sections") ?? SECTIONS.join(","))
    .split(",")
    .filter((s): s is SectionId => (SECTIONS as readonly string[]).includes(s));
  const scale = Number(arg("--scale") ?? 1);
  const workers = arg("--workers");
  const jobs = buildPlan(new Set(requested), scale);
  const started = Date.now();
  console.log(`balance:report — ${jobs.length} jobs, scale ${scale}`);
  const results = await runPool(
    jobs,
    workers ? Number(workers) : undefined,
    (key, done, total) => {
      if (done % 10 === 0 || done === total)
        console.log(
          `  ${done}/${total} (${key}) ${Math.round((Date.now() - started) / 1000)} s`,
        );
    },
  );
  const json = arg("--json");
  if (json) fs.writeFileSync(json, JSON.stringify([...results.entries()]));
  const out = arg("--out") ?? path.join("docs", "balance", "latest.md");
  const body = [
    "# Balance report (real engine)",
    "",
    `Generated by \`npm run balance:report\` (scale ${scale}, ${jobs.length} jobs, ${Math.round((Date.now() - started) / 1000)} s). Bots, not humans: "average" = Normal. Draws count ½. Intervals are Wilson 95 %. ✘ = outside 40–60 % (matchups) or ±15 % (value).`,
    "",
    listsSection(),
    renderFactionSection(
      results,
      "classic",
      "Classic Skirmish 4v4 — auto-fill lists (average v average)",
    ),
    renderFactionSection(
      results,
      "reinforced",
      "Reinforced Skirmish — 1000 pool / 250 cap, auto-fill opening, balanced plans",
    ),
    renderFactionSection(
      results,
      "preset",
      "200-pt quick-build presets (classic)",
    ),
    renderAceSection(results),
    renderDogfightSection(results),
    renderDifficultySection(results),
    renderScenarioSection(results),
    renderShipsSection(results),
  ].join("\n");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, body);
  console.log(`wrote ${out}`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
