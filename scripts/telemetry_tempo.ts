/**
 * telemetry_tempo — tempo experiment (never changes the game's constants):
 * replays duels, squad battles and both skill gates under what-if tempos on
 * the sims' flight clock (TempoVariant): maneuver cycle 500 / 625 / 750 ms ×
 * special / boost / barrel-roll recharge ×1 / ×1.5 / ×2, plus longer cycles
 * whose attack cap stays at the engine's 500 ms (to separate "longer cycle"
 * from "fewer attacks per second").
 * Writes docs/telemetry/tempo-experiment-data.md.
 *
 * Usage: npm run telemetry:tempo -- [--scale 1]   (scale multiplies every sample size)
 */

import * as fs from "fs";
import { CYCLE_DURATION_MS } from "../src/config";
import {
  summarizeCell,
  type CellStats,
} from "../src/simulation/telemetryBattery";
import type { TempoVariant } from "../src/simulation/TempoVariant";
import { runJobs, type BatteryJob } from "./telemetry_pool";

const OUT = "docs/telemetry/tempo-experiment-data.md";
/** Samples per variant and cell (before --scale). */
const SAMPLES: Readonly<Record<string, number>> = {
  "dogfight:average v average": 48,
  "squad:average v average": 32,
  gate1: 120,
  gate2: 48,
};
const CYCLES = [CYCLE_DURATION_MS, 625, 750] as const;
const MULTIPLIERS = [1, 1.5, 2] as const;
const PERCENT = 100;
const MS_PER_S = 1000;

interface Variant {
  readonly id: string;
  readonly tempo: TempoVariant;
}

function variants(): Variant[] {
  const grid = CYCLES.flatMap((cycleMs) =>
    MULTIPLIERS.map((m) => ({
      id: `c${cycleMs}-x${m}`,
      tempo: {
        cycleMs,
        specialCooldownMultiplier: m,
        attackInterval: "cycle" as const,
      },
    })),
  );
  const fixed = CYCLES.filter((c) => c !== CYCLE_DURATION_MS).map(
    (cycleMs) => ({
      id: `c${cycleMs}-x1-fixed`,
      tempo: {
        cycleMs,
        specialCooldownMultiplier: 1,
        attackInterval: "fixed" as const,
      },
    }),
  );
  return [...grid, ...fixed];
}

function arg(flag: string): string | undefined {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function row(
  v: Variant,
  s: (cell: string) => CellStats,
  base: (cell: string) => CellStats,
): string {
  const sec = (ms: number): string => `${(ms / MS_PER_S).toFixed(0)}s`;
  const pct = (x: number): string => `${(x * PERCENT).toFixed(0)}%`;
  const delta = (cell: string): string =>
    `${((s(cell).meanMs / base(cell).meanMs - 1) * PERCENT).toFixed(0)}%`;
  const duel = s("dogfight:average v average");
  const squad = s("squad:average v average");
  return (
    `| ${v.tempo.cycleMs} | ×${v.tempo.specialCooldownMultiplier} | ${v.tempo.attackInterval} | ` +
    `${sec(duel.medianMs)} · ${sec(duel.meanMs)} (${delta("dogfight:average v average")}) | ${duel.dps.toFixed(2)} | ` +
    `${sec(squad.medianMs)} · ${sec(squad.meanMs)} (${delta("squad:average v average")}) | ${sec(squad.medianFirstKillMs)} | ${squad.dps.toFixed(2)} | ` +
    `${squad.specialsPerShipMinute.toFixed(1)} | ${pct(s("gate1").side1WinRate)} | ${pct(s("gate2").side1WinRate)} |`
  );
}

async function main(): Promise<void> {
  const scale = Number(arg("--scale") ?? 1);
  const list = variants();
  const jobs: BatteryJob[] = list.flatMap((v) =>
    Object.entries(SAMPLES).map(([cellId, n]) => ({
      key: `${v.id}|${cellId}`,
      cellId,
      seeds: Math.max(1, Math.round(n * scale)),
      tempo: v.tempo,
    })),
  );
  const started = Date.now();
  const results = await runJobs(jobs, (key, done, total) =>
    console.log(`[${done}/${total}] ${key}`),
  );
  const stats = (v: Variant) => (cell: string) =>
    summarizeCell(results.get(`${v.id}|${cell}`) ?? []);
  const base = stats(list[0]!);
  const lines = [
    "# Tempo experiment — raw data",
    "",
    `Generated by \`npm run telemetry:tempo\` (scale ${scale}, ${((Date.now() - started) / MS_PER_S).toFixed(0)} s). ` +
      `Samples per variant: ${Object.entries(SAMPLES)
        .map(([c, n]) => `${c} ${Math.round(n * scale)}`)
        .join(", ")}.`,
    "",
    "| cycle (ms) | specials | attack cap | duel avg v avg median · mean (Δ mean) | duel DPS | squad 4v4 avg median · mean (Δ mean) | squad first kill | squad DPS | squad specials / ship·min | gate 1 expert win | gate 2 squad win |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
    ...list.map((v) => row(v, stats(v), base)),
    "",
    "Gate thresholds: gate 1 ≥ 85% (expert beats novice), gate 2 ≥ 70% (coordinated average squad beats solo experts).",
    'attack cap "cycle" = one attack and one hit-immunity window per (longer) cycle; "fixed" = the engine\'s 500 ms.',
    "",
  ];
  fs.mkdirSync("docs/telemetry", { recursive: true });
  fs.writeFileSync(OUT, lines.join("\n"));
  console.log(lines.join("\n"));
}

void main();
