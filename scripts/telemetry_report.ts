/**
 * telemetry_report — the headless telemetry battery: bot-vs-bot matches on
 * the real shared code paths (DuelTempoSim, skill arena squads, Scenario
 * matches, Survival nodes) per mode × tier pairing, summarised as match
 * length (p10 / median / p90), time to first kill, damage per second, hit
 * rate, special actions per ship-minute and the share decided by timeout.
 * Writes docs/telemetry/latest-report.md.
 *
 * Usage: npm run telemetry:report -- [--seeds 80] [--out docs/telemetry/latest-report.md]
 */

import * as fs from "fs";
import * as path from "path";
import { BATTERY_CELLS } from "../src/simulation/batteryCells";
import {
  CELL_HEADER,
  CELL_SEPARATOR,
  cellRow,
  summarizeCell,
} from "../src/simulation/telemetryBattery";
import { CYCLE_DURATION_MS, DURABILITY_SCALE } from "../src/config";
import { runJobs } from "./telemetry_pool";

const DEFAULT_SEEDS = 80;
/** Survival cells count whole runs, which are cheap per sample. */
const SURVIVAL_RUNS = 200;
const DEFAULT_OUT = "docs/telemetry/latest-report.md";

function arg(flag: string): string | undefined {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

async function main(): Promise<void> {
  const seeds = Number(arg("--seeds") ?? DEFAULT_SEEDS);
  const out = arg("--out") ?? DEFAULT_OUT;
  const started = Date.now();
  const results = await runJobs(
    BATTERY_CELLS.map((cell) => ({
      key: cell.id,
      cellId: cell.id,
      seeds: cell.id.startsWith("survival") ? SURVIVAL_RUNS : seeds,
    })),
    (key, done, total) => console.log(`[${done}/${total}] ${key}`),
  );
  const rows = BATTERY_CELLS.map((cell) =>
    cellRow(cell.mode, cell.pairing, summarizeCell(results.get(cell.id) ?? [])),
  );
  const markdown = [
    "# Telemetry battery — latest report",
    "",
    `Generated by \`npm run telemetry:report\` (${seeds} seeds per cell, survival: ${SURVIVAL_RUNS} runs; ` +
      `${((Date.now() - started) / 1000).toFixed(0)} s). Engine tempo: cycle ${CYCLE_DURATION_MS} ms, ` +
      `DURABILITY_SCALE ${DURABILITY_SCALE}. Bots fly every ship (BotPilot through the player's controls).`,
    "",
    CELL_HEADER,
    CELL_SEPARATOR,
    ...rows,
    "",
    "Columns: match length from weapons-live to the last kill (a timeout counts its full limit);",
    "first kill = median time to the first ship destroyed; DPS = both sides' damage per second;",
    "hit rate = hits / attacks; specials = K-turn, Segnor, Tallon, boost and barrel roll per ship per",
    "minute (Survival: the player's fleet only); side-1 wins = side 1 / A / the player's side.",
    "Survival rows come from whole simulated runs (autopilot flagship, see SurvivalRunSim) and do not",
    "track damage or gunnery.",
    "",
  ].join("\n");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, markdown);
  console.log(
    `\n${CELL_HEADER}\n${CELL_SEPARATOR}\n${rows.join("\n")}\n\nWrote ${out}`,
  );
}

void main();
