/**
 * LabReport — the movement lab's results as a short markdown document
 * (docs/balance/movement-lab.md).
 *
 * Pure: no Phaser, no I/O.
 */

import type { LabReport } from "./MovementLab";
import type { TurnResult } from "./LabTurns";
import { DEFAULT_ANALOG_TUNING, formatAnalogTuning } from "../../core/analogTuning";

/**
 * @param value - A number.
 * @param digits - Decimals.
 * @returns The number, or "never" for Infinity.
 */
function num(value: number, digits = 0): string {
  return Number.isFinite(value) ? value.toFixed(digits) : "never";
}

/**
 * @param turn - A turn result.
 * @returns "time ms / radius px / overshoot °" cells.
 */
function turnCells(turn: TurnResult): string {
  return `${num(turn.timeMs)} | ${num(turn.radiusPx)} | ${num(turn.overshootDeg)}`;
}

/**
 * @param report - The lab's results.
 * @returns The table of input feel (latency and turn-rate constancy).
 */
function feelTable(report: LabReport): string[] {
  const { latency, constancy } = report;
  return [
    "## Input feel (arrow held)",
    "",
    "| engine | press → 1° (mean / worst ms) | press → 5° (mean ms) | turn rate (°/s) | rate variation (σ/mean) |",
    "|---|---|---|---|---|",
    ...(["template", "analog"] as const).map(
      (engine) =>
        `| ${engine} | ${num(latency[engine].meanMs1Deg)} / ${num(latency[engine].worstMs1Deg)} | ${num(latency[engine].meanMs5Deg)} | ${num(constancy[engine].meanDegPerSec)} | ${num(constancy[engine].variation, 2)} |`,
    ),
    "",
  ];
}

/**
 * @param report - The lab's results.
 * @returns The turn-quality table.
 */
function turnTable(report: LabReport): string[] {
  return [
    "## Turns (U-turn = 180°, correction = 45°)",
    "",
    "Rows with accidental rolls include the barrel-roll slide in the position jerk (a 112 px jump).",
    "",
    "| throttle | engine | pilot | U-turn ms | U-turn radius px | U-turn overshoot ° | 45° ms | 45° radius px | 45° overshoot ° | heading accel RMS °/s² | position jerk RMS px/s³ | accidental rolls (U-turn) |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ...report.turns.map(
      (row) =>
        `| ${row.speed} | ${row.engine} | ${row.pilot} | ${turnCells(row.uTurn)} | ${turnCells(row.correction)} | ${num(row.smoothness.headingAccelRms)} | ${num(row.smoothness.positionJerkRms)} | ${row.uTurn.rolls} |`,
    ),
    "",
  ];
}

/**
 * @param report - The lab's results.
 * @returns The duel table.
 */
function duelTable(report: LabReport): string[] {
  const { options } = report;
  return [
    `## Duel vs a novice bot (${options.seeds} seeds × ${options.durationMs / 1000} s, throttle ${options.speeds[0]}, no weapons)`,
    "",
    "Target in the 75° / 250 px wedge; a shot = a 500 ms cycle with the target in the wedge at some moment.",
    "",
    "| engine | pilot | % time in wedge | shots / min | accidental rolls / min |",
    "|---|---|---|---|---|",
    ...report.duels.map(
      (row) =>
        `| ${row.engine} | ${row.pilot} | ${num(row.duel.wedgePercent, 1)} | ${num(row.duel.shotsPerMinute, 1)} | ${num(row.duel.rollsPerMinute, 1)} |`,
    ),
    "",
  ];
}

/**
 * @param report - The lab's results.
 * @returns The turn-rate-scale sweep table.
 */
function sweepTable(report: LabReport): string[] {
  return [
    "## Analog turn-rate sweep (× the template's per-cycle rates)",
    "",
    "| rate × | pilot | U-turn ms | U-turn radius px | % time in wedge | shots / min |",
    "|---|---|---|---|---|---|",
    ...report.sweep.map(
      (row) =>
        `| ${row.rateScale} | ${row.pilot} | ${num(row.uTurn.timeMs)} | ${num(row.uTurn.radiusPx)} | ${num(row.duel.wedgePercent, 1)} | ${num(row.duel.shotsPerMinute, 1)} |`,
    ),
    "",
  ];
}

/**
 * @param report - The lab's results.
 * @returns The markdown document.
 */
export function formatLabReport(report: LabReport): string {
  const { options } = report;
  return [
    "# Movement lab: template vs analog steering",
    "",
    `Generated by \`npm run movement:lab\` (ship \`${options.definitionId}\`, throttles ${options.speeds.join(", ")}). Deterministic: fixed 60 Hz ticks, seeded duels. Analog rows fly the default analog tuning (${formatAnalogTuning(DEFAULT_ANALOG_TUNING)}; the tabletop preset is 45° / 90°, see docs/specs/flight-controls.md).`,
    "Pilots: *proportional* presses what the heading error asks for (template: Q/E for ≥ 18°, the arrow for ≥ 5°: the best template thresholds of a sweep; analog: the one key while there is error);",
    "*tapper* only taps the arrow (100 ms down, a pulse every 233 ms: never reads as a roll) while there is error; *fast-tapper* pulses every 150 ms (75 ms down), inside the 220 ms barrel-roll double-tap window.",
    "",
    ...feelTable(report),
    ...turnTable(report),
    ...duelTable(report),
    ...sweepTable(report),
  ].join("\n");
}
